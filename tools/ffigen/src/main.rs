//! Writes the guest imports' glue, for the host and both SDKs, from sdk/mim.ffi
//!
//! `cargo run -p ffigen`, from anywhere in the repo. The outputs are checked in.

use indoc::formatdoc;
use std::collections::HashSet;
use std::path::Path;
use std::process::ExitCode;
use std::{fmt, fs};
use winnow::ascii::{dec_uint, space0, space1};
use winnow::combinator::{alt, cut_err, delimited, fail, not, preceded, separated, seq};
use winnow::error::{StrContext, StrContextValue};
use winnow::prelude::*;
use winnow::token::{one_of, take_while};

const TABLE: &str = "sdk/mim.ffi";
const SPDX: &str = "SPDX-License-Identifier: MIT OR GPL-2.0-only";
const NOTE: &str = "GENERATED by tools/ffigen from sdk/mim.ffi: don't edit. Change the table, then run `cargo run -p ffigen`.";

// More than this many WASM values per call is a sign the import wants a struct
const MAX_WASM_ARGS: usize = 8;
// Names the thunks and handlers use themselves
const RESERVED: [&str; 5] = ["m", "mem", "sp", "ctx", "runtime"];
// Names that would break the generated C, C++ (sdk/cpp/ffi.h) or Rust: keywords, and the C types
// the generated code uses. Function names only clash in Rust, since the C ones get a prefix.
#[rustfmt::skip]
const KEYWORDS: &[&str] = &[
    // C
    "auto", "break", "case", "char", "const", "continue", "default", "do", "double", "else", "enum",
    "extern", "float", "for", "goto", "if", "inline", "int", "long", "register", "restrict",
    "return", "short", "signed", "sizeof", "static", "struct", "switch", "typedef", "union",
    "unsigned", "void", "volatile", "while",
    "int32_t", "uint32_t", "int64_t", "uint64_t", "uint8_t", "size_t",
    // C++, on top of C
    "alignas", "alignof", "and", "and_eq", "asm", "bitand", "bitor", "bool", "catch", "char8_t",
    "char16_t", "char32_t", "class", "co_await", "co_return", "co_yield", "compl", "concept",
    "const_cast", "consteval", "constexpr", "constinit", "decltype", "delete", "dynamic_cast",
    "explicit", "export", "false", "friend", "mutable", "namespace", "new", "noexcept", "not",
    "not_eq", "nullptr", "operator", "or", "or_eq", "private", "protected", "public",
    "reinterpret_cast", "requires", "static_assert", "static_cast", "template", "this",
    "thread_local", "throw", "true", "try", "typeid", "typename", "using", "virtual", "wchar_t",
    "xor", "xor_eq",
    // Rust, including the reserved ones
    "_", "abstract", "as", "async", "await", "become", "box", "crate", "dyn", "final", "fn", "gen",
    "impl", "in", "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub",
    "ref", "self", "super", "trait", "type", "typeof", "unsafe", "unsized", "use", "where", "yield",
];

type Generate = fn(&Table) -> String;

// What gets written where
const OUTPUTS: [(&str, Generate); 4] = [
    ("runtime/guest/ffi.h", host_h),
    ("runtime/guest/ffi.c", host_c),
    ("sdk/rust/src/ffi.rs", rust),
    ("sdk/cpp/ffi.h", guest_c),
];

//===----------------------------------------------------------------------===//
// The table
//===----------------------------------------------------------------------===//

/// One WASM value
#[derive(Clone, Copy)]
enum Scalar {
    I32,
    U32,
    I64,
    U64,
    F32,
    F64,
}

#[derive(Clone, Copy)]
enum Ty {
    Scalar(Scalar),
    /// A guest address, one i32. The handler checks what it points at.
    Ptr,
    /// A guest address and a length, two i32s. Checked before the handler runs.
    Bytes,
}

struct Arg {
    name: String,
    ty: Ty,
}

struct Func {
    name: String,
    args: Vec<Arg>,
}

struct Const {
    name: String,
    value: u64,
}

enum Item {
    Const(Const),
    Func(Func),
}

#[derive(Default)]
struct Table {
    consts: Vec<Const>,
    funcs: Vec<Func>,
}

impl Scalar {
    /// Its C type, its Rust type and its letter in a wasm3 signature
    fn names(self) -> (&'static str, &'static str, char) {
        match self {
            Scalar::I32 => ("int32_t", "i32", 'i'),
            Scalar::U32 => ("uint32_t", "u32", 'i'),
            Scalar::I64 => ("int64_t", "i64", 'I'),
            Scalar::U64 => ("uint64_t", "u64", 'I'),
            Scalar::F32 => ("float", "f32", 'f'),
            Scalar::F64 => ("double", "f64", 'F'),
        }
    }

    fn c(self) -> &'static str {
        self.names().0
    }

    fn rust(self) -> &'static str {
        self.names().1
    }

    fn wasm3(self) -> char {
        self.names().2
    }
}

impl fmt::Display for Ty {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        match self {
            Ty::Scalar(s) => f.write_str(s.rust()),
            Ty::Ptr => f.write_str("ptr"),
            Ty::Bytes => f.write_str("bytes"),
        }
    }
}

impl Arg {
    /// The WASM values this argument arrives as, named as the generated code names them
    fn values(&self) -> Vec<(String, Scalar)> {
        match self.ty {
            Ty::Scalar(s) => vec![(self.name.clone(), s)],
            Ty::Ptr => vec![(self.name.clone(), Scalar::U32)],
            Ty::Bytes => vec![
                (self.name.clone(), Scalar::U32),
                (format!("{}_len", self.name), Scalar::U32),
            ],
        }
    }

    /// Its parameters in host_<name>
    fn host_params(&self) -> Vec<String> {
        match self.ty {
            Ty::Bytes => vec![
                format!("const uint8_t *const {}", self.name),
                format!("const uint32_t {}_len", self.name),
            ],
            _ => self
                .values()
                .into_iter()
                .map(|(n, s)| format!("const {} {n}", s.c()))
                .collect(),
        }
    }

    /// What the thunk passes for it
    fn host_call(&self) -> Vec<String> {
        match self.ty {
            Ty::Bytes => vec![
                format!("m.base + {}", self.name),
                format!("{}_len", self.name),
            ],
            _ => vec![self.name.clone()],
        }
    }

    /// Its parameters in the C declaration a guest imports
    fn guest_c_params(&self) -> Vec<String> {
        match self.ty {
            Ty::Scalar(s) => vec![format!("{} {}", s.c(), self.name)],
            Ty::Ptr => vec![format!("const void *{}", self.name)],
            Ty::Bytes => vec![
                format!("const void *{}", self.name),
                format!("uint32_t {}_len", self.name),
            ],
        }
    }

    /// Its parameters in the Rust declaration a guest imports
    fn rust_params(&self) -> Vec<String> {
        match self.ty {
            Ty::Scalar(s) => vec![format!("{}: {}", self.name, s.rust())],
            Ty::Ptr => vec![format!("{}: *const core::ffi::c_void", self.name)],
            Ty::Bytes => vec![
                format!("{}: *const u8", self.name),
                format!("{}_len: u32", self.name),
            ],
        }
    }
}

impl Func {
    fn values(&self) -> impl Iterator<Item = (String, Scalar)> + '_ {
        self.args.iter().flat_map(Arg::values)
    }

    fn signature(&self) -> String {
        format!(
            "v({})",
            self.values().map(|(_, s)| s.wasm3()).collect::<String>()
        )
    }

    // What's wrong with it that the grammar can't see
    fn problems(&self) -> Vec<String> {
        let keyword = KEYWORDS
            .contains(&self.name.as_str())
            .then(|| format!("`{}` is a C, C++ or Rust keyword", self.name));
        let mut seen = HashSet::new();
        let names = self
            .values()
            .map(|(n, _)| n)
            .filter(|n| {
                RESERVED.contains(&n.as_str())
                    || KEYWORDS.contains(&n.as_str())
                    || !seen.insert(n.clone())
            })
            .map(|n| format!("bad or duplicate argument name `{n}`"));
        let slots = self.values().count();
        let too_many = (slots > MAX_WASM_ARGS)
            .then(|| format!("{slots} WASM arguments, more than {MAX_WASM_ARGS}"));
        keyword.into_iter().chain(names).chain(too_many).collect()
    }
}

impl Item {
    fn name(&self) -> &str {
        match self {
            Item::Const(c) => &c.name,
            Item::Func(f) => &f.name,
        }
    }

    fn problems(&self) -> Vec<String> {
        match self {
            Item::Func(f) => f.problems(),
            // a C enum constant is an int
            Item::Const(c) => (c.value > i32::MAX as u64)
                .then(|| format!("{} is too big for C, at most {}", c.value, i32::MAX))
                .into_iter()
                .collect(),
        }
    }
}

//===----------------------------------------------------------------------===//
// Parsing: one item per line, `#` starts a comment
//===----------------------------------------------------------------------===//

fn expected(what: &'static str) -> StrContext {
    StrContext::Expected(StrContextValue::Description(what))
}

fn ident(i: &mut &str) -> ModalResult<String> {
    (
        one_of(('a'..='z', '_')),
        take_while(0.., ('a'..='z', '0'..='9', '_')),
    )
        .take()
        .map(str::to_owned)
        .context(expected("a lower_case name"))
        .parse_next(i)
}

fn ty(i: &mut &str) -> ModalResult<Ty> {
    alt((
        "i32".value(Ty::Scalar(Scalar::I32)),
        "u32".value(Ty::Scalar(Scalar::U32)),
        "i64".value(Ty::Scalar(Scalar::I64)),
        "u64".value(Ty::Scalar(Scalar::U64)),
        "f32".value(Ty::Scalar(Scalar::F32)),
        "f64".value(Ty::Scalar(Scalar::F64)),
        "ptr".value(Ty::Ptr),
        "bytes".value(Ty::Bytes),
    ))
    .context(expected("i32, u32, i64, u64, f32, f64, ptr or bytes"))
    .parse_next(i)
}

fn arg(i: &mut &str) -> ModalResult<Arg> {
    // past the `:` it's an argument, so a bad type is reported where it is
    seq!(Arg { name: ident, _: (space0, ':', space0), ty: cut_err(ty) }).parse_next(i)
}

// `const <name> <value>`
fn constant(i: &mut &str) -> ModalResult<Const> {
    seq!(Const {
        name: ident,
        _: space1,
        value: dec_uint.context(expected("a non-negative integer")),
    })
    .parse_next(i)
}

// `fn <name> (<arg>, ...)`
fn func(i: &mut &str) -> ModalResult<Func> {
    seq!(Func {
        name: ident,
        _: space0,
        args: delimited(
            ('(', space0),
            separated(0.., arg, (space0, ',', space0)),
            (space0, ')').context(expected("`,` or `)`")),
        ),
        // ponytail: no import returns a value yet; add it with read_events
        _: not((space0, "->")).context(expected("no `->`: imports can't return values yet")),
    })
    .parse_next(i)
}

fn item(i: &mut &str) -> ModalResult<Item> {
    alt((
        preceded(("const", space1), cut_err(constant)).map(Item::Const),
        preceded(("fn", space1), cut_err(func)).map(Item::Func),
        fail.context(expected("`const` or `fn`")),
    ))
    .parse_next(i)
}

/// The table, or every problem found in it, each starting with "sdk/mim.ffi:<line>:"
fn parse(text: &str) -> Result<Table, Vec<String>> {
    let parsed: Vec<Result<(usize, Item), String>> = text
        .lines()
        .enumerate()
        .map(|(n, line)| (n + 1, line.split('#').next().unwrap_or("").trim()))
        .filter(|(_, line)| !line.is_empty())
        .map(|(n, line)| {
            item.parse(line)
                .map(|it| (n, it))
                .map_err(|e| format!("{TABLE}:{n}:\n{e}"))
        })
        .collect();

    let mut names = HashSet::new();
    let errors: Vec<String> = parsed
        .iter()
        .flat_map(|r| match r {
            Err(e) => vec![e.clone()],
            Ok((n, it)) => {
                let duplicate = (!names.insert(it.name().to_owned()))
                    .then(|| format!("duplicate name `{}`", it.name()));
                duplicate
                    .into_iter()
                    .chain(it.problems())
                    .map(|p| format!("{TABLE}:{n}: {p}"))
                    .collect()
            }
        })
        .collect();
    if !errors.is_empty() {
        return Err(errors);
    }

    let table = parsed
        .into_iter()
        .flatten()
        .fold(Table::default(), |mut t, (_, it)| {
            match it {
                Item::Const(c) => t.consts.push(c),
                Item::Func(f) => t.funcs.push(f),
            }
            t
        });
    // C has no empty array, and guest_imports[] would be one
    Some(table).filter(|t| !t.funcs.is_empty()).ok_or_else(|| {
        vec![format!(
            "{TABLE}: no `fn`: there has to be at least one import"
        )]
    })
}

//===----------------------------------------------------------------------===//
// Output
//===----------------------------------------------------------------------===//

fn header() -> String {
    format!("// {SPDX}\n// {NOTE}\n\n")
}

// "name(a, b)" on one line, or one per line once there are five or more, as clang-format keeps them
fn c_call(name: &str, params: &[String], end: &str) -> String {
    if params.len() < 5 {
        format!("{name}({}){end}", params.join(", "))
    } else {
        format!("{name}(\n    {}\n){end}", params.join(",\n    "))
    }
}

fn each<T>(items: &[T], line: impl Fn(&T) -> String) -> String {
    items.iter().map(line).collect()
}

// The constants as an anonymous enum, then a blank line; or nothing, since C has no empty enum
fn c_enum(prefix: &str, consts: &[Const]) -> String {
    if consts.is_empty() {
        return String::new();
    }
    let lines = each(consts, |c| {
        format!("    {prefix}{} = {},\n", c.name, c.value)
    });
    format!("enum {{\n{lines}}};\n\n")
}

fn host_h(t: &Table) -> String {
    let consts = c_enum("guest_", &t.consts);
    let handlers = each(&t.funcs, |f| {
        let params: Vec<String> = std::iter::once("const guest_mem_t *const mem".to_owned())
            .chain(f.args.iter().flat_map(Arg::host_params))
            .collect();
        c_call(&format!("const char *host_{}", f.name), &params, ";\n")
    });
    header()
        + &formatdoc! {"
            #pragma once

            #include <stdbool.h>
            #include <stddef.h>
            #include <stdint.h>

            #ifdef __cplusplus
            extern \"C\" {{
            #endif

            {consts}// The guest's linear memory, as one import call sees it
            typedef struct guest_mem_t {{
                uint8_t *base;
                size_t size;
            }} guest_mem_t;

            // True if [ptr, ptr + len) is inside the guest's memory; written so ptr + len can't wrap
            static inline bool guest_mem_has(const guest_mem_t *const mem, const uint32_t ptr, const size_t len) {{
                return len <= mem->size && ptr <= mem->size - len;
            }}

            // Written by hand. Each returns NULL, or a message that traps the guest. `bytes` arguments
            // are already checked and arrive as host pointers; `ptr` arguments are guest addresses.
            {handlers}
            struct M3Runtime;
            struct M3ImportContext;

            // One import from module \"mim\": its name, its wasm3 signature, and the thunk that calls host_<name>
            typedef struct guest_import_t {{
                const char *name;
                const char *signature;
                const void *(*thunk)(struct M3Runtime *runtime, struct M3ImportContext *ctx, uint64_t *sp, void *mem);
            }} guest_import_t;

            extern const guest_import_t guest_imports[];
            extern const size_t guest_import_count;

            #ifdef __cplusplus
            }}
            #endif
        "}
}

fn thunk(f: &Func) -> String {
    let name = &f.name;
    let args = f
        .args
        .iter()
        .map(|a| format!("{}: {}", a.name, a.ty))
        .collect::<Vec<_>>()
        .join(", ");
    let reads: String = f
        .values()
        .enumerate()
        .map(|(slot, (n, s))| {
            format!(
                "    const {c} {n} = *(const {c} *)&sp[{slot}];\n",
                c = s.c()
            )
        })
        .collect();
    let checks: String = f
        .args
        .iter()
        .filter(|a| matches!(a.ty, Ty::Bytes))
        .map(|a| {
            formatdoc! {"
                    if (!guest_mem_has(&m, {n}, {n}_len)) {{
                        return \"mim.{name}: {n} outside guest memory\";
                    }}
                ", n = a.name}
            .lines()
            .map(|l| format!("    {l}\n"))
            .collect::<String>()
        })
        .collect();
    let call: Vec<String> = std::iter::once("&m".to_owned())
        .chain(f.args.iter().flat_map(Arg::host_call))
        .collect();
    let call = c_call(&format!("    return host_{name}"), &call, ";\n");
    formatdoc! {"

        // mim.{name}({args})
        static const void *thunk_{name}(IM3Runtime runtime, IM3ImportContext ctx, uint64_t *sp, void *mem) {{
            (void)ctx;
            const guest_mem_t m = {{mem, m3_GetMemorySize(runtime)}};
        {reads}{checks}{call}}}
    "}
}

fn host_c(t: &Table) -> String {
    let thunks = each(&t.funcs, thunk);
    let table = each(&t.funcs, |f| {
        format!(
            "    {{\"{0}\", \"{1}\", thunk_{0}}},\n",
            f.name,
            f.signature()
        )
    });
    header()
        + &formatdoc! {"
            #include \"runtime/guest/ffi.h\"

            #include \"wasm3.h\"

            // Each thunk reads its arguments from wasm3's stack, one 64-bit slot each, checks every
            // `bytes` argument against the guest's memory, then calls the handler.
            {thunks}
            const guest_import_t guest_imports[] = {{
            {table}}};
            const size_t guest_import_count = sizeof(guest_imports) / sizeof(guest_imports[0]);
        "}
}

fn rust(t: &Table) -> String {
    let consts = each(&t.consts, |c| {
        format!(
            "pub const {}: usize = {};\n",
            c.name.to_uppercase(),
            c.value
        )
    });
    let decls = each(&t.funcs, |f| {
        let params: Vec<String> = f.args.iter().flat_map(Arg::rust_params).collect();
        format!("    pub fn {}({});\n", f.name, params.join(", "))
    });
    header()
        + &formatdoc! {"
            {consts}
            // wasm32v1-none links without --allow-undefined: imports must name their module
            #[link(wasm_import_module = \"mim\")]
            unsafe extern \"C\" {{
            {decls}}}
        "}
}

fn guest_c(t: &Table) -> String {
    let consts = c_enum("mim_", &t.consts);
    let decls = each(&t.funcs, |f| {
        let params: Vec<String> = f.args.iter().flat_map(Arg::guest_c_params).collect();
        let attr = format!(
            "__attribute__((import_module(\"mim\"), import_name(\"{}\")))",
            f.name
        );
        c_call(&format!("{attr} void mim_{}", f.name), &params, ";\n")
    });
    header()
        + &formatdoc! {"
            // Plain C, so C and C++ guests can both include it

            #pragma once

            #include <stdint.h>

            #ifdef __cplusplus
            extern \"C\" {{
            #endif

            {consts}{decls}
            #ifdef __cplusplus
            }}
            #endif
        "}
}

fn run() -> Result<(), Vec<String>> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let text = fs::read_to_string(root.join(TABLE)).map_err(|e| vec![format!("{TABLE}: {e}")])?;
    let table = parse(&text)?;
    OUTPUTS.iter().try_for_each(|(path, generate)| {
        fs::write(root.join(path), generate(&table)).map_err(|e| vec![format!("{path}: {e}")])
    })
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(errors) => {
            for e in &errors {
                eprintln!("ffigen: {e}");
            }
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn signatures() {
        let t = parse("const n 3\nfn log (level: u32, text: bytes)  # comment\nfn f (a: f32, b: i64, p: ptr)\n").unwrap();
        let sigs: Vec<String> = t.funcs.iter().map(Func::signature).collect();
        assert_eq!(sigs, ["v(iii)", "v(fIi)"]);
        assert_eq!(t.consts[0].value, 3);
    }

    #[test]
    fn rejects() {
        let Err(errors) = parse(
            "fn a (x: str)\nfn b (x: u32) -> u32\nfn c (x: u32, x: u32)\nfn d (t: bytes, t_len: u32)\n\
             fn e (mem: u32)\nconst c 1\nconst k -1\nfn g (a: bytes, b: bytes, c: bytes, d: bytes, e: u32)\nwhat\n\
             fn h (int: u32)\nfn type (a: u32)\nfn _ (a: u32)\nconst big 2147483648\nfn i (this: u32)\n",
        ) else {
            panic!("accepted a bad table");
        };
        let lines: Vec<&str> = errors
            .iter()
            .map(|e| e.split(':').nth(1).unwrap())
            .collect();
        let expected: Vec<String> = (1..=14).map(|n| n.to_string()).collect();
        assert_eq!(lines, expected, "{errors:#?}");
    }

    #[test]
    fn edges() {
        // the largest constant C takes
        assert!(parse("const n 2147483647\nfn f ()").is_ok());
        // no constants: no enum at all, since C has no empty one
        let t = parse("fn f ()").unwrap();
        assert!(!host_h(&t).contains("enum") && !guest_c(&t).contains("enum"));
        // no imports: guest_imports[] would be an empty array
        assert!(parse("const n 1").is_err());
    }
}
